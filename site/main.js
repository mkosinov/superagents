const badgeEl = document.getElementById("detail-badge");
const titleEl = document.getElementById("detail-title");
const textEl = document.getElementById("detail-text");
const factsEl = document.getElementById("detail-facts");
const gateButtons = document.querySelectorAll(".gate");

function showGate(key) {
  const g = GATES[key];
  if (!g) return;
  badgeEl.textContent = g.badge;
  titleEl.textContent = g.title;
  textEl.textContent = g.text;
  factsEl.innerHTML = "";
  for (const f of g.facts) {
    const span = document.createElement("span");
    span.textContent = "· " + f;
    factsEl.appendChild(span);
  }
  gateButtons.forEach((b) => b.classList.toggle("active", b.dataset.gate === key));
}

gateButtons.forEach((b) => b.addEventListener("click", () => showGate(b.dataset.gate)));

// стартовая карточка — самый показательный гейт
showGate("g1b");
